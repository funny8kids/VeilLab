// Generates contracts/src/Poseidon.sol from the circomlibjs Poseidon constants.
//
// TESTNET / SPIKE ONLY.
//
// Provenance:
//   - The circuit uses circomlib 2.0.5 (circuits/membership.circom).
//   - The constants in circomlibjs/src/poseidon_constants.json are the reference
//     Poseidon C/M tables used by circomlibjs's buildPoseidonReference() and
//     buildPoseidon(); both were cross-checked against the fixture.
//   - This script emits a small, loop-based BN254 Poseidon library. It is not
//     an optimized implementation, but it is easy to audit against the
//     reference loop in circomlibjs/src/poseidon_reference.js.
//
// Usage (from circuits/):
//   node scripts/gen-poseidon-solidity.mjs
//
// Output:
//   ../contracts/src/Poseidon.sol
//
// Do not edit the generated file by hand. Re-run this script after a
// deliberate circomlib/Poseidon parameter change and update the circuit setup.

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import url from "node:url";

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const circuitsDir = path.resolve(__dirname, "..");
const repoRoot = path.resolve(circuitsDir, "..");
const constantsPath = path.join(
  circuitsDir,
  "node_modules",
  "circomlibjs",
  "src",
  "poseidon_constants.json",
);
const outputPath = path.join(repoRoot, "contracts", "src", "Poseidon.sol");

const FIELD_MODULUS =
  21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const DOMAIN_NODE = 0x7665696c706f6f6c2d6d65726b6c652d7631n;
const ROUNDS_F = 8;
// circomlib 2.0.5, PoseidonEx: N_ROUNDS_P[t - 2].
const ROUNDS_P = [56, 57, 56, 60, 60, 63, 64, 63, 60, 66, 60, 65, 70, 60, 64, 68];

// t = nInputs + 1. The pool only needs hash3, but hash5/hash6 are included so
// the Solidity output can be checked against the circuit's off-chain hashes.
const ARITIES = [
  { t: 4, inputs: 3, fn: "hash3" },
  { t: 6, inputs: 5, fn: "hash5" },
  { t: 7, inputs: 6, fn: "hash6" },
];

const raw = await readFile(constantsPath, "utf8");
const constants = JSON.parse(raw);
const constantsHash = createHash("sha256").update(raw).digest("hex");

function hex32(value) {
  return BigInt(value).toString(16).padStart(64, "0");
}

function words(values) {
  return values.map(hex32).join("");
}

function validate(t, index, c, m) {
  const rounds = ROUNDS_F + ROUNDS_P[index];
  if (c.length !== rounds * t) {
    throw new Error(
      `C table for t=${t}: expected ${rounds * t} entries, got ${c.length}`,
    );
  }
  if (m.length !== t || m.some((row) => row.length !== t)) {
    throw new Error(`M table for t=${t}: expected ${t}x${t}`);
  }
  for (const value of [...c, ...m.flat()]) {
    if (BigInt(value) >= FIELD_MODULUS) {
      throw new Error(`constant out of BN254 scalar field for t=${t}`);
    }
  }
}

let body = "";
for (const { t, inputs, fn } of ARITIES) {
  const index = t - 2;
  const c = constants.C[index];
  const m = constants.M[index];
  if (!c || !m) {
    throw new Error(`missing Poseidon constants for t=${t}`);
  }
  validate(t, index, c, m);

  const args = Array.from({ length: inputs }, (_, i) => `uint256 a${i}`).join(", ");
  const assignments = Array.from(
    { length: inputs },
    (_, i) => `        state[${i + 1}] = a${i};`,
  ).join("\n");

  body += `
    /* ------------------------------------------------------------------ */
    /* Poseidon(${inputs}) = state width ${t}, ${ROUNDS_P[index]} partial rounds     */
    /* ------------------------------------------------------------------ */

    bytes private constant C${t} = hex"${words(c)}";
    bytes private constant M${t} = hex"${words(m.flat())}";

    /// @notice Poseidon(${inputs}) over BN254, circomlib 2.0.5 parameters.
    function ${fn}(${args}) internal pure returns (uint256) {
        uint256[7] memory state;
${assignments}
        return _permute(state, ${t}, ${ROUNDS_P[index]}, C${t}, M${t});
    }
`;
}

const source = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// @title Poseidon (BN254 / circomlib 2.0.5)
/// @notice Loop-based Poseidon reference implementation for the VeilPool spike.
/// @dev GENERATED FILE. Do not edit by hand.
///
///      Generated by circuits/scripts/gen-poseidon-solidity.mjs from
///      circomlibjs/src/poseidon_constants.json.
///      Constants SHA-256: ${constantsHash}
///
///      This implementation follows the Poseidon reference loop:
///        state = [0, inputs...]
///        for each round:
///          state[i] += C[round * t + i]
///          state[i] = state[i]^5   (full round, or only state[0] in a partial round)
///          state = M * state
///        output = state[0]
///
///      It is intentionally simple instead of gas-optimized. It has NOT been
///      audited. It is only used by the local Groth16 spike contract.
library Poseidon {
    /// @notice BN254 scalar field modulus.
    uint256 internal constant FIELD_MODULUS =
        ${FIELD_MODULUS};
    /// @notice Domain tag for Merkle nodes: "veilpool-merkle-v1".
    uint256 internal constant DOMAIN_NODE =
        0x7665696c706f6f6c2d6d65726b6c652d7631;

${body}
    /// @dev Poseidon permutation. The state has room for t=7; only state[0..t-1]
    ///      is read and written. The c and m inputs are the row-major constant
    ///      tables from circomlibjs, encoded as 32-byte big-endian words.
    function _permute(
        uint256[7] memory state,
        uint256 t,
        uint256 partialRounds,
        bytes memory c,
        bytes memory m
    ) private pure returns (uint256) {
        uint256 rounds = ${ROUNDS_F} + partialRounds;
        uint256[7] memory next;

        for (uint256 r = 0; r < rounds; r++) {
            for (uint256 i = 0; i < t; i++) {
                state[i] = addmod(state[i], _word(c, (r * t + i) * 32), FIELD_MODULUS);
            }

            bool fullRound = r < ${ROUNDS_F} / 2 || r >= ${ROUNDS_F} / 2 + partialRounds;
            if (fullRound) {
                for (uint256 i = 0; i < t; i++) {
                    state[i] = _pow5(state[i]);
                }
            } else {
                state[0] = _pow5(state[0]);
            }

            // next[i] = sum_j M[i][j] * state[j] (row-major M).
            for (uint256 i = 0; i < t; i++) {
                next[i] = _mixRow(state, t, m, i);
            }
            for (uint256 i = 0; i < t; i++) {
                state[i] = next[i];
            }
        }

        return state[0];
    }

    /// @dev One row of the MDS multiplication: sum_j M[row][j] * state[j].
    function _mixRow(uint256[7] memory state, uint256 t, bytes memory m, uint256 row)
        private
        pure
        returns (uint256 acc)
    {
        for (uint256 j = 0; j < t; j++) {
            acc = addmod(
                acc,
                mulmod(state[j], _word(m, (row * t + j) * 32), FIELD_MODULUS),
                FIELD_MODULUS
            );
        }
    }

    /// @dev x^5 mod p.
    function _pow5(uint256 x) private pure returns (uint256) {
        uint256 x2 = mulmod(x, x, FIELD_MODULUS);
        uint256 x4 = mulmod(x2, x2, FIELD_MODULUS);
        return mulmod(x4, x, FIELD_MODULUS);
    }

    /// @dev Read the 32-byte big-endian word at the supplied offset from a bytes blob.
    function _word(bytes memory data, uint256 offset) private pure returns (uint256 value) {
        assembly {
            value := mload(add(add(data, 32), offset))
        }
    }
}
`;

await writeFile(outputPath, source, "utf8");
console.log(`wrote ${path.relative(repoRoot, outputPath)}`);
console.log(`constants sha256 = ${constantsHash}`);
console.log(`domain node      = 0x${hex32(DOMAIN_NODE)}`);
