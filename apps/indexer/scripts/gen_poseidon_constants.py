#!/usr/bin/env python3
"""Generate the Python Poseidon(3) constants for the VeilPool indexer.

Provenance
----------
The membership circuit uses circomlib 2.0.5 ``Poseidon(3)``. The canonical
round-constant and MDS tables are the ones shipped by circomlibjs in
``circuits/node_modules/circomlibjs/src/poseidon_constants.json``. This is the
same source used by ``circuits/scripts/gen-poseidon-solidity.mjs`` for the
Solidity ``Poseidon.sol`` reference implementation.

For state width ``t = nInputs + 1 = 4`` the table index is ``t - 2 = 2``:

* ``C[2]`` has ``(8 + 56) * 4 = 256`` words (round-major, one word per state
  element per round);
* ``M[2]`` is the 4x4 row-major MDS matrix.

Usage (defaults resolve from the repository root)::

    python apps/indexer/scripts/gen_poseidon_constants.py

    # explicit paths:
    python apps/indexer/scripts/gen_poseidon_constants.py \
        --source circuits/node_modules/circomlibjs/src/poseidon_constants.json \
        --output apps/indexer/veilpool_indexer/poseidon_constants.py

The generated ``poseidon_constants.py`` is committed source. Re-run this script
after a deliberate circomlib/Poseidon parameter change and update the circuit
setup as well.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

FIELD_MODULUS = 21888242871839275222246405745257275088548364400416034343698204186575808495617
ROUNDS_F = 8
ROUNDS_P = 56
WIDTH = 4
TABLE_INDEX = WIDTH - 2

DEFAULT_SOURCE = Path("circuits/node_modules/circomlibjs/src/poseidon_constants.json")
DEFAULT_OUTPUT = Path("apps/indexer/veilpool_indexer/poseidon_constants.py")


def _repo_root() -> Path:
    # apps/indexer/scripts/gen_poseidon_constants.py -> repository root
    return Path(__file__).resolve().parents[3]


def _resolve(path: Path, root: Path) -> Path:
    return path if path.is_absolute() else root / path


def _as_int(value: object) -> int:
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        return int(value, 0)
    raise TypeError(f"unexpected Poseidon constant type: {type(value).__name__}")


def _hex_blob(values: list[int], words_per_line: int = 4) -> str:
    words = [format(value, "064x") for value in values]
    lines = [
        '    "' + "".join(words[offset : offset + words_per_line]) + '"'
        for offset in range(0, len(words), words_per_line)
    ]
    return "\n".join(lines)


def generate(source: Path, output: Path) -> tuple[str, int, int]:
    raw = source.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    constants = json.loads(raw)

    try:
        c_values = constants["C"][TABLE_INDEX]
        m_rows = constants["M"][TABLE_INDEX]
    except (KeyError, IndexError, TypeError) as exc:
        raise SystemExit(f"{source}: missing C/M table index {TABLE_INDEX}") from exc

    expected_c = WIDTH * (ROUNDS_F + ROUNDS_P)
    if len(c_values) != expected_c:
        raise SystemExit(
            f"{source}: C[{TABLE_INDEX}] has {len(c_values)} entries, expected {expected_c}"
        )
    if len(m_rows) != WIDTH or any(len(row) != WIDTH for row in m_rows):
        raise SystemExit(f"{source}: M[{TABLE_INDEX}] is not {WIDTH}x{WIDTH}")

    c_ints = [_as_int(value) for value in c_values]
    m_ints = [[_as_int(value) for value in row] for row in m_rows]
    for value in [*c_ints, *(value for row in m_ints for value in row)]:
        if not 0 <= value < FIELD_MODULUS:
            raise SystemExit(f"{source}: constant is outside the BN254 scalar field")

    try:
        source_label = source.resolve().relative_to(_repo_root()).as_posix()
    except ValueError:
        source_label = source.as_posix()

    body = f'''"""Poseidon(3) round constants for BN254 (circomlib 2.0.5).

GENERATED FILE - DO NOT EDIT BY HAND.

Generated by apps/indexer/scripts/gen_poseidon_constants.py from
{source_label}
(table index t - 2 = {TABLE_INDEX}, state width {WIDTH}).

Source SHA-256: {digest}

Parameters: {ROUNDS_F} full rounds + {ROUNDS_P} partial rounds, state width
{WIDTH}. The caller supplies the domain tag as the first hash input, so
Poseidon(3) is invoked as hash3(DOMAIN_NODE, left, right).

C is round-major: C[round * t + state_index]. M is row-major.
"""

SOURCE_SHA256 = "{digest}"
ROUNDS_F = {ROUNDS_F}
ROUNDS_P = {ROUNDS_P}
WIDTH = {WIDTH}

C4_HEX = (
{_hex_blob(c_ints)}
)

M4_HEX = (
{_hex_blob([value for row in m_ints for value in row])}
)


def _split_words(blob: str) -> tuple[int, ...]:
    if len(blob) % 64 != 0:
        raise ValueError("Poseidon constant blob is not a whole number of words")
    return tuple(int(blob[offset : offset + 64], 16) for offset in range(0, len(blob), 64))


C4 = _split_words(C4_HEX)
_M4_WORDS = _split_words(M4_HEX)
M4 = tuple(
    _M4_WORDS[offset : offset + WIDTH] for offset in range(0, len(_M4_WORDS), WIDTH)
)

if len(C4) != WIDTH * (ROUNDS_F + ROUNDS_P):
    raise ValueError("Poseidon C4 constant table has the wrong length")
if len(M4) != WIDTH or any(len(row) != WIDTH for row in M4):
    raise ValueError("Poseidon M4 constant table has the wrong shape")
'''

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(body, encoding="utf-8", newline="\n")
    return digest, len(c_ints), len(m_ints)


def main(argv: list[str] | None = None) -> int:
    root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--source",
        type=Path,
        default=DEFAULT_SOURCE,
        help=f"circomlibjs poseidon_constants.json (default: {DEFAULT_SOURCE.as_posix()})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"generated Python module (default: {DEFAULT_OUTPUT.as_posix()})",
    )
    args = parser.parse_args(argv)

    source = _resolve(args.source, root)
    output = _resolve(args.output, root)
    if not source.is_file():
        raise SystemExit(f"Poseidon constants source not found: {source}")

    digest, c_count, m_count = generate(source, output)
    print(f"wrote {output}")
    print(f"source sha256 = {digest}")
    print(f"C4 entries = {c_count}; M4 rows = {m_count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
